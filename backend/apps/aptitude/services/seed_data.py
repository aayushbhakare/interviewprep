def seed_initial_aptitude_bank() -> int:
    """
    Populates the shared aptitude question bank with the 45 curated Cognitive Foundation baseline questions.
    Returns count of newly seeded questions.
    """
    created_count = 0
    for item in CURATED_APTITUDE_SEED:
        existing = AptitudeQuestion.objects.filter(
            category=item["category"],
            question_text=item["question_text"],
        ).first()

        if not existing:
            q_obj = AptitudeQuestion.objects.create(
                category=item["category"],
                topic=item["topic"],
                difficulty=item["difficulty"],
                status=AptitudeQuestion.STATUS_APPROVED,
                question_text=item["question_text"],
                options=item["options"],
                correct_option_index=item["correct_option_index"],
                explanation=item["explanation"],
                is_active=True,
            )
            AptitudeQuestionVersion.objects.create(
                question=q_obj,
                version_number=1,
                question_text=item["question_text"],
                options=item["options"],
                correct_option_index=item["correct_option_index"],
                explanation=item["explanation"],
                validation_status=AptitudeQuestionVersion.VALIDATION_VALID,
                is_published=True,
            )
            created_count += 1
        else:
            # Ensure version 1 exists
            AptitudeQuestionVersion.objects.get_or_create(
                question=existing,
                version_number=1,
                defaults={
                    "question_text": item["question_text"],
                    "options": item["options"],
                    "correct_option_index": item["correct_option_index"],
                    "explanation": item["explanation"],
                    "validation_status": AptitudeQuestionVersion.VALIDATION_VALID,
                    "is_published": True,
                },
            )

    return created_count
